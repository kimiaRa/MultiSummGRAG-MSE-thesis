#!/usr/bin/env python3
"""
E6 -- manual error audit of the five pipeline reports, cross-referenced
against E2's automated flags.

Read-only. No model calls, no network calls, no pipeline stage run. Reuses
poisson_exact_ci from evaluation/e2_internal_consistency.py (this project's
own Part 2 module) -- same Garwood/chi-squared method E2 itself uses, so E6
and E2 rates are computed the same way and are comparable.

Input: evaluation/results/manual_error_catalogue.csv -- 31 hand-reviewed
candidate errors across the 5 pipeline reports, each with a VERDICT
(TP/FP/UNCLEAR) and, for FP/UNCLEAR, a MY_NOTE giving the reason for
rejection.

Cross-reference method (task step 6): a verified (VERDICT==TP) manual error
is counted as "also caught by E2" if evaluation/results/e2_flags.csv has a
row for the same city AND the same report section (flag's section_heading
contains the catalogue's section keyword, e.g. "Types" matches "Types of
Food Sharing Initiatives") whose flagged sentence shares at least one
numeric token with the manual entry's quoted_claim. Numbers are compared as
normalised strings (commas stripped, trailing '%' stripped) so "1,000" and
"1000" or "34%" and "34" match.

The section gate matters and is not cosmetic: city+number alone gives two
false matches on this data. Milan's M03 ("food banks (26) outnumber
community gardens (17) by 34.0% to 11.6%", section Types) shares the digit
34 with the CS-4 flag on a *different* milan sentence (the Municipio
district claim, section Geographic Distribution) purely because both
sentences happen to misattribute the same donut-chart "other" value (34%)
-- CS-4's own justification text names the Municipio constituents only, not
food banks. London's M15 ("Westminster's 33 FSIs represent over a third of
London's total", section Notable) shares the digit 33 with a CS-5 flag on a
different london sentence (the per-capita/population claim, section
Geographic Distribution) purely because both sentences mention Westminster.
Requiring the same section, which both the manual catalogue and e2_flags.csv
independently record, removes both without needing any fuzzier text
matching. This is independent of e2_flags.csv's own VERDICT column -- the
question is whether E2's check *fired* on the same claim, not whether E2's
own human review kept it a TP; in every case found here the two VERDICT
columns agree (see printed detail).

Outputs:
    evaluation/results/e6_manual_audit.csv   per-city rate + CI table
    evaluation/E6_SUMMARY.md                 full report
    (prints the cross-reference detail table for the write-up)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pandas as pd

_HERE = Path(__file__).resolve().parent
_EVAL_DIR = _HERE.parent
sys.path.insert(0, str(_EVAL_DIR))
import e2_internal_consistency as e2mod  # noqa: E402 -- reused: poisson_exact_ci

RESULTS_DIR = _EVAL_DIR / "results"
CATALOGUE_FILE = RESULTS_DIR / "manual_error_catalogue.csv"
E2_FLAGS_FILE = RESULTS_DIR / "e2_flags.csv"
E2_SUMMARY_FILE = RESULTS_DIR / "e2_summary.csv"

N_WORDS = {"barcelona": 1308, "brighton": 1192, "dublin": 1255, "london": 1244, "milan": 1319}
CITIES = sorted(N_WORDS)

NUM_RE = re.compile(r"\d[\d,]*(?:\.\d+)?%?")


def _read(path: Path) -> pd.DataFrame:
    return pd.read_csv(path, dtype=str, keep_default_na=False)


def _section_matches(cat_section: str, flag_section_heading: str) -> bool:
    return cat_section.strip().lower() in flag_section_heading.strip().lower()


def _numbers(text: str) -> set[str]:
    """Numeric tokens in text, normalised (commas stripped, '%' stripped,
    trailing '.0' stripped) so '1,000', '1000' and '1000.0' all match, and
    '34%' matches a bare '34'."""
    out = set()
    for tok in NUM_RE.findall(text):
        norm = tok.replace(",", "").rstrip("%")
        if norm.endswith(".0"):
            norm = norm[:-2]
        if norm:
            out.add(norm)
    return out


def main() -> None:
    cat = _read(CATALOGUE_FILE)
    flags = _read(E2_FLAGS_FILE)

    md: list[str] = []
    rows: list[dict] = []

    md.append("# E6 -- Manual error audit of the pipeline reports\n")
    md.append(
        "Read-only, no model calls, no network calls, no pipeline stage run. "
        "Generated by `evaluation/scripts/e6_manual_audit.py`, which reuses "
        "`poisson_exact_ci` from `evaluation/e2_internal_consistency.py` (Part 2) "
        "-- the same exact-Poisson (Garwood/chi-squared) method E2 itself uses, "
        "so the two rates in this document and in E2_SUMMARY_v2.md are computed "
        "identically and are directly comparable.\n"
    )
    md.append(
        "**Scope.** 31 candidate errors were hand-identified by close reading of "
        "the five pipeline reports (barcelona, brighton, dublin, london, milan) "
        "and logged in `evaluation/results/manual_error_catalogue.csv`, each "
        "with a `VERDICT` (TP / FP / UNCLEAR) recorded on a second pass and, for "
        "every FP or UNCLEAR, a `MY_NOTE` giving the reason for rejection. "
        "Baseline reports were not manually audited here; this document does "
        "not compare pipeline vs. baseline defect rates.\n"
    )

    # ── Step 1: screening outcome ──────────────────────────────────────
    md.append("## 1. Screening outcome\n")
    verdict_counts = cat["VERDICT"].value_counts()
    n_total = len(cat)
    n_tp = int(verdict_counts.get("TP", 0))
    n_fp = int(verdict_counts.get("FP", 0))
    n_unclear = int(verdict_counts.get("UNCLEAR", 0))
    assert n_tp + n_fp + n_unclear == n_total, "VERDICT values outside {TP, FP, UNCLEAR}"

    prec_incl = n_tp / n_total
    prec_excl = n_tp / (n_tp + n_fp) if (n_tp + n_fp) else float("nan")

    md.append(
        f"31 candidates were screened by hand: **{n_tp} TP, {n_fp} FP, {n_unclear} UNCLEAR**.\n"
    )
    md.append(
        "This screening precision is itself part of the audit's result, not a "
        "discarded intermediate: of everything that *looked like* an error on "
        "first pass, roughly a third did not survive a second, more careful "
        "look (an invented population figure that turned out to be flagged "
        "correctly is not the same class of finding as a claim that seemed "
        "off but check out on re-reading the report's own scope, e.g. M06, "
        "M17 below).\n"
    )
    md.append(f"- **Candidate precision including UNCLEAR as non-error:** {n_tp}/{n_total} = {100*prec_incl:.1f}%")
    md.append(f"- **Candidate precision excluding UNCLEAR (TP/(TP+FP)):** {n_tp}/{n_tp + n_fp} = {100*prec_excl:.1f}%\n")
    rows.append({"section": "screening", "city": "", "metric": "n_total", "value": n_total})
    rows.append({"section": "screening", "city": "", "metric": "n_tp", "value": n_tp})
    rows.append({"section": "screening", "city": "", "metric": "n_fp", "value": n_fp})
    rows.append({"section": "screening", "city": "", "metric": "n_unclear", "value": n_unclear})
    rows.append({"section": "screening", "city": "", "metric": "precision_incl_unclear", "value": round(prec_incl, 4)})
    rows.append({"section": "screening", "city": "", "metric": "precision_excl_unclear", "value": round(prec_excl, 4)})

    # ── Step 2: verified errors by city, rate per 1000 words, Poisson CI ─
    md.append("## 2. Verified errors by city\n")
    tp = cat[cat["VERDICT"] == "TP"].copy()

    # M30/M31 are logged with city == "ALL" (a single tautology/corpus-vs-world
    # pattern observed identically in all 5 reports) rather than one row per
    # city; both are FP here, so this only matters if that ever changes.
    per_city_tp: dict[str, int] = {c: 0 for c in CITIES}
    all_rows = tp[tp["city"] == "ALL"]
    city_rows = tp[tp["city"] != "ALL"]
    for c, sub in city_rows.groupby("city"):
        per_city_tp[c] = per_city_tp.get(c, 0) + len(sub)
    n_all_pattern = len(all_rows) * len(CITIES)  # would apply once per city if ever TP

    md.append("| city | n_words | n_verified_errors | errors/1,000 words | 95% CI (exact Poisson) |")
    md.append("|---|---|---|---|---|")
    total_errors = 0
    total_words = 0
    for c in CITIES:
        n_err = per_city_tp[c]
        n_w = N_WORDS[c]
        rate = 1000 * n_err / n_w
        lo, hi = e2mod.poisson_exact_ci(n_err, n_w / 1000.0)
        md.append(f"| {c} | {n_w} | {n_err} | {rate:.3f} | {lo:.3f} - {hi:.3f} |")
        rows.append({"section": "per_city_rate", "city": c, "metric": "n_words", "value": n_w})
        rows.append({"section": "per_city_rate", "city": c, "metric": "n_verified_errors", "value": n_err})
        rows.append({"section": "per_city_rate", "city": c, "metric": "errors_per_1000_words", "value": round(rate, 4)})
        rows.append({"section": "per_city_rate", "city": c, "metric": "ci95_lower", "value": round(lo, 4)})
        rows.append({"section": "per_city_rate", "city": c, "metric": "ci95_upper", "value": round(hi, 4)})
        total_errors += n_err
        total_words += n_w

    pooled_rate = 1000 * total_errors / total_words
    pooled_lo, pooled_hi = e2mod.poisson_exact_ci(total_errors, total_words / 1000.0)
    md.append(f"| **pooled** | **{total_words}** | **{total_errors}** | **{pooled_rate:.3f}** | **{pooled_lo:.3f} - {pooled_hi:.3f}** |\n")
    rows.append({"section": "pooled_rate", "city": "pooled", "metric": "n_words", "value": total_words})
    rows.append({"section": "pooled_rate", "city": "pooled", "metric": "n_verified_errors", "value": total_errors})
    rows.append({"section": "pooled_rate", "city": "pooled", "metric": "errors_per_1000_words", "value": round(pooled_rate, 4)})
    rows.append({"section": "pooled_rate", "city": "pooled", "metric": "ci95_lower", "value": round(pooled_lo, 4)})
    rows.append({"section": "pooled_rate", "city": "pooled", "metric": "ci95_upper", "value": round(pooled_hi, 4)})

    if n_all_pattern:
        md.append(
            f"*(2 candidates, M30/M31, are logged once each against `city=ALL` because they name "
            f"a pattern observed identically in all 5 reports rather than a single-city defect; "
            f"both are FP so they do not enter the counts above. See section 5.)*\n"
        )

    # ── Step 3: verified errors by error_type ──────────────────────────
    md.append("## 3. Verified errors by error_type\n")
    type_counts = tp["error_type"].value_counts()
    md.append("| error_type | n |")
    md.append("|---|---|")
    for etype, n in type_counts.items():
        md.append(f"| {etype} | {n} |")
        rows.append({"section": "by_error_type", "city": "", "metric": etype, "value": int(n)})
    md.append("")

    # ── Step 4: every TP in full ─────────────────────────────────────
    md.append("## 4. Every verified error (TP), in full\n")
    md.append("| id | city | section | quoted claim | stated | correct | error_type |")
    md.append("|---|---|---|---|---|---|---|")
    for _, r in tp.sort_values("id").iterrows():
        md.append(
            f"| {r['id']} | {r['city']} | {r['section']} | {r['quoted_claim']} "
            f"| {r['stated_value']} | {r['correct_value']} | {r['error_type']} |"
        )
    md.append("")

    # ── Step 5: every FP/UNCLEAR with rejection reason ─────────────────
    md.append("## 5. Every FP and UNCLEAR, with reason for rejection\n")
    rejected = cat[cat["VERDICT"] != "TP"].sort_values(["VERDICT", "id"])
    md.append("| id | city | VERDICT | quoted claim | reason (MY_NOTE) |")
    md.append("|---|---|---|---|---|")
    for _, r in rejected.iterrows():
        note = r["MY_NOTE"].strip() or "(no note recorded)"
        md.append(f"| {r['id']} | {r['city']} | {r['VERDICT']} | {r['quoted_claim']} | {note} |")
    md.append("")

    # ── Step 6: cross-reference with E2 ─────────────────────────────────
    md.append("## 6. Cross-reference with E2's automated checks\n")
    md.append(
        "Match rule: a verified (TP) manual error counts as *also caught by E2* if "
        "`e2_flags.csv` has a row for the same city **and the same report section** "
        "(flag's `section_heading` contains the catalogue's `section` keyword) whose "
        "flagged `sentence` shares at least one numeric token with the manual entry's "
        "`quoted_claim` (numbers normalised: commas stripped, `%` stripped, so "
        "`1,000`/`34%` match `1000`/`34`). The section gate removes two matches that "
        "city+number alone would produce purely from a coincidentally shared digit "
        "across two *different* sentences discussing different things -- see the "
        "worked examples in the module docstring of `e6_manual_audit.py`. This "
        "checks whether the same claim tripped an automated check at all, independent "
        "of e2_flags.csv's own VERDICT column.\n"
    )

    caught_rows = []
    only_manual_rows = []
    for _, r in tp.sort_values("id").iterrows():
        city = r["city"]
        if city == "ALL":
            continue
        claim_nums = _numbers(r["quoted_claim"])
        candidates = flags[
            (flags["city"] == city)
            & flags["section_heading"].apply(lambda s: _section_matches(r["section"], s))
        ]
        match = None
        for _, fr in candidates.iterrows():
            flag_nums = _numbers(fr["sentence"])
            if claim_nums & flag_nums:
                match = fr
                break
        if match is not None:
            caught_rows.append((r, match))
        else:
            only_manual_rows.append(r)

    n_caught = len(caught_rows)
    n_manual_only = len(only_manual_rows)
    md.append(f"- **Verified manual errors also caught by an automated E2 check: {n_caught}**")
    md.append(f"- **Verified manual errors caught by the manual audit only: {n_manual_only}**\n")
    rows.append({"section": "cross_reference", "city": "", "metric": "n_caught_by_both", "value": n_caught})
    rows.append({"section": "cross_reference", "city": "", "metric": "n_manual_only", "value": n_manual_only})

    md.append("**Caught by both:**\n")
    md.append("| manual id | city | quoted claim | matching E2 check | E2's own VERDICT |")
    md.append("|---|---|---|---|---|")
    for r, fr in caught_rows:
        md.append(f"| {r['id']} | {r['city']} | {r['quoted_claim']} | {fr['check']} | {fr['VERDICT']} |")
    md.append("")

    md.append("**Manual audit only (no matching E2 flag for that city/claim):**\n")
    md.append("| manual id | city | quoted claim | error_type |")
    md.append("|---|---|---|---|")
    for r in only_manual_rows:
        md.append(f"| {r['id']} | {r['city']} | {r['quoted_claim']} | {r['error_type']} |")
    md.append("")

    # ── Step 7: structural blind spots ──────────────────────────────────
    md.append("## 7. Error classes the automated checks structurally cannot reach\n")
    md.append(
        "Three classes of verified error have no automated check in E2 that could "
        "have caught them, each for a different structural reason:\n"
    )
    md.append(
        "**Cross-section self-contradiction.** CS-3 (cross-section contradiction "
        "detection) was prototyped for E2 and explicitly rejected -- it fired 121 "
        "times on a single arithmetically-clean baseline report, meaning it was "
        "keying on stylistic rephrasing across sections rather than genuine numeric "
        "contradiction, and was dropped (see `evaluation/e2_internal_consistency.py`'s "
        "`CS3_REJECTION_NOTE` constant for the full rejection rationale). "
        "No cross-section check of any kind runs in E2. "
        "Example: **M07** (london, Geographic) -- the report states \"nine "
        "districts ... each host only one FSI\" in one paragraph and \"three "
        "districts -- Lewisham, Barnet, and Sutton -- each have only one FSI\" two "
        "paragraphs later, a direct self-contradiction within the same section "
        "that no single-sentence check can see.\n"
    )
    md.append(
        "**Semantic contradiction with no arithmetic signature.** A claim can "
        "contradict another claim in plain language without either side being a "
        "number CS-1/CS-2/CS-4 could check against a total. Example: **M05** "
        "(milan, Operational) -- \"none are volunteer-based\" against \"141 "
        "non-commercial, encompassing voluntary and charitable efforts\" in the "
        "same paragraph. There is no percentage-of-total or majority-keyword "
        "pattern here for E2 to key on; the contradiction is between the words "
        "\"none\" and \"voluntary\", not between two numbers.\n"
    )
    md.append(
        "**Fabricated named-entity figures.** A specific number attached to a "
        "specific named organisation, invented outright, produces text that is "
        "internally consistent -- it does not conflict with any total, keyword, "
        "or other figure in the report, so nothing in E2 has a reason to flag it. "
        "Example: **M23** (brighton, Reach) -- \"The In the Bag Project reaches "
        "10,000+ individuals through food banks\" is a self-contained claim about "
        "a single named initiative; it was flagged only by checking the figure "
        "against `fsi_enriched.jsonl` and finding no supporting record at all, "
        "not by any arithmetic or keyword pattern.\n"
    )

    # E2's own verified (TP-only) pooled rate, computed the same way, for a
    # concrete side-by-side rather than a qualitative assertion in Step 8.
    e2_tp = flags[flags["VERDICT"] == "TP"]
    e2_tp_n = len(e2_tp)
    e2_rate = 1000 * e2_tp_n / total_words
    e2_lo, e2_hi = e2mod.poisson_exact_ci(e2_tp_n, total_words / 1000.0)
    rows.append({"section": "e2_comparison", "city": "pooled", "metric": "e2_verified_n", "value": e2_tp_n})
    rows.append({"section": "e2_comparison", "city": "pooled", "metric": "e2_verified_rate_per_1000_words", "value": round(e2_rate, 4)})
    rows.append({"section": "e2_comparison", "city": "pooled", "metric": "e2_verified_ci95_lower", "value": round(e2_lo, 4)})
    rows.append({"section": "e2_comparison", "city": "pooled", "metric": "e2_verified_ci95_upper", "value": round(e2_hi, 4)})

    # ── Step 8: framing for the thesis ──────────────────────────────────
    md.append("## 8. Framing for the thesis\n")
    md.append(
        f"**E2's verified automated rate is a lower bound on defect density, not an "
        f"estimate of it.** E2 checks four narrow, syntactic patterns (percentage-of-"
        f"total mismatches, majority/most misuse, in-sentence aggregate arithmetic, "
        f"invented per-capita/population bases) and, by construction, can only ever "
        f"report defects that happen to fall into one of those four shapes. Section 7 "
        f"above gives three concrete classes of real, verified error -- cross-section "
        f"contradiction, semantic contradiction without arithmetic, and fabricated "
        f"named-entity figures -- that no automated check here can structurally reach. "
        f"Section 6 shows this is not theoretical: only {n_caught} of the "
        f"{n_tp} verified manual TPs were also caught by an automated E2 check; "
        f"{n_manual_only} were found only by manual audit.\n"
    )
    md.append(
        f"**The manual audit is the primary error evidence.** Its pooled rate "
        f"({pooled_rate:.2f} errors/1,000 words, 95% CI {pooled_lo:.2f}-{pooled_hi:.2f}) "
        f"is roughly {pooled_rate / e2_rate:.1f}x E2's own verified pooled rate "
        f"(restricting `e2_flags.csv` to `VERDICT == 'TP'`, the same filter "
        f"E2_SUMMARY_v2.md section 2 (\"Verified (VERDICT=TP only) -- the number "
        f"to cite\") instructs: {e2_tp_n}/{total_words} words = {e2_rate:.2f} "
        f"errors/1,000 words, 95% CI {e2_lo:.2f}-{e2_hi:.2f}, overlapping this "
        f"audit's CI). The gap exists precisely because the manual audit is not "
        f"limited to E2's four syntactic shapes -- it is a close human reading of "
        f"the whole report, scored with the same VERDICT-column protocol E2 itself "
        f"uses.\n"
    )
    md.append(
        "**The two are complementary, not redundant.** E2 is cheap, exhaustive over "
        "its four patterns, and reproducible without human judgement; the manual audit "
        "is expensive, non-exhaustive by construction (a close reading, not a formal "
        "proof of completeness), but reaches error classes E2 cannot. Reporting only "
        "E2's rate would understate the defect density; reporting only the manual rate "
        "would lose E2's reproducibility and its use as a cheap regression check. Both "
        "numbers belong in the thesis, explicitly labelled: E2 = lower bound / automated "
        "/ reproducible; E6 = primary estimate / manual / non-exhaustive.\n"
    )

    out_md = _EVAL_DIR / "E6_SUMMARY.md"
    out_md.write_text("\n".join(md), encoding="utf-8")

    # Written via csv.writer, not pandas.to_csv: rows mix int counts and
    # float rates in the same "value" column, and pandas upcasts the whole
    # column to float64 (31 -> "31.0") the moment any row is a float. This
    # keeps each value's own Python type (int stays "31", float stays
    # "0.6452") without reshaping the tidy long format.
    import csv

    out_csv = RESULTS_DIR / "e6_manual_audit.csv"
    with out_csv.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["section", "city", "metric", "value"])
        for r in rows:
            writer.writerow([r["section"], r["city"], r["metric"], r["value"]])

    print(f"Wrote {out_md}")
    print(f"Wrote {out_csv}")
    print(f"\nScreening: {n_tp} TP, {n_fp} FP, {n_unclear} UNCLEAR "
          f"(precision incl. UNCLEAR: {100*prec_incl:.1f}%, excl.: {100*prec_excl:.1f}%)")
    print(f"Pooled verified rate: {pooled_rate:.3f} / 1000 words, CI [{pooled_lo:.3f}, {pooled_hi:.3f}]")
    print(f"Caught by both: {n_caught}; manual-only: {n_manual_only}")


if __name__ == "__main__":
    main()
